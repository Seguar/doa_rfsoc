#!/usr/bin/env python3
"""Generate a Vivado block-design Tcl script from a PYNQ hardware handoff (HWH).

The boot pair in PS/python/boot (doa_mts.bit/.hwh) was built from a block
design whose Tcl was never committed: the checked-in PL/doa_mts.tcl matches the
older PL/out pair instead. The HWH, however, lists every cell (with its full
hierarchical name, VLNV and parameters), every interface and port connection
and the address map, which is enough to recreate the design.

Usage:  python3 hwh2bd.py BOOT.hwh OUT_DIR

Writes OUT_DIR/bd_from_hwh.tcl (creates the design in an open project; needs
the procedure apply_hwh_params from bd_helpers.tcl) and OUT_DIR/hwh_params.tcl
(a dict of cell path -> {param value ...}).

The Tcl creates cells with the newest installed version of each IP (Vivado
2025.2 instead of 2022.2). Parameters are applied generically by
apply_hwh_params: only names that exist as CONFIG.<name> on the new cell are
set, so derived and read-only model parameters are skipped. Compare the
resulting HWH with hwhdiff.py to prove the recreation.
"""
import os
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict, OrderedDict

SKIP_PARAMS = {'Component_Name', 'EDK_IPTYPE', 'EDK_SPECIAL', 'c_component_name',
               'C_COMPONENT_NAME', 'TLM_COMPONENT_NAME', 'C_EST_POWER_SUMMARY'}


def tcl_quote(s):
    s = '' if s is None else str(s)
    return '{' + s.replace('\\', '\\\\').replace('{', '\\{').replace('}', '\\}') + '}'


def parse(path):
    root = ET.parse(path).getroot()
    mods = OrderedDict()
    for m in root.iter('MODULE'):
        full = m.get('FULLNAME').lstrip('/')
        params = OrderedDict((p.get('NAME'), p.get('VALUE'))
                             for p in m.findall('PARAMETERS/PARAMETER'))
        ports = []
        for p in m.findall('PORTS/PORT'):
            ports.append(dict(name=p.get('NAME'), dir=p.get('DIR'), sig=p.get('SIGNAME'),
                              left=p.get('LEFT'), right=p.get('RIGHT')))
        buses = []
        for b in m.findall('BUSINTERFACES/BUSINTERFACE'):
            pm = [x.get('PHYSICAL') for x in b.iter('PORTMAP')]
            buses.append(dict(name=b.get('NAME'), busname=b.get('BUSNAME'), type=b.get('TYPE'),
                              vlnv=b.get('VLNV'), ports=pm))
        mods[m.get('INSTANCE')] = dict(full=full, vlnv=m.get('VLNV'), params=params,
                                       ports=ports, buses=buses)
    ext_ports = [dict(name=p.get('NAME'), dir=p.get('DIR'), sig=p.get('SIGNAME'),
                      left=p.get('LEFT'), right=p.get('RIGHT'))
                 for p in root.findall('EXTERNALPORTS/PORT')]
    ext_intf = [dict(name=b.get('NAME'), busname=b.get('BUSNAME'), type=b.get('TYPE'))
                for b in root.findall('EXTERNALINTERFACES/BUSINTERFACE')]
    memranges = []
    for mr in root.iter('MEMRANGE'):
        if mr.get('MASTERBUSINTERFACE'):
            memranges.append(dict(inst=mr.get('INSTANCE'), slave=mr.get('SLAVEBUSINTERFACE'),
                                  base=mr.get('BASEVALUE'), high=mr.get('HIGHVALUE'),
                                  master=mr.get('MASTERBUSINTERFACE'),
                                  owner=None))
    # owner of each memrange = the MODULE containing it
    for m in root.iter('MODULE'):
        for mr in m.iter('MEMRANGE'):
            for x in memranges:
                if (x['inst'], x['slave'], x['base']) == (mr.get('INSTANCE'), mr.get('SLAVEBUSINTERFACE'), mr.get('BASEVALUE')):
                    x['owner'] = m.get('INSTANCE')
    return mods, ext_ports, ext_intf, memranges


def generate(hwh, outdir):
    mods, ext_ports, ext_intf, memranges = parse(hwh)
    L = []
    w = L.append
    w('# Generated by hwh2bd.py from %s - do not edit by hand.' % os.path.basename(hwh))
    w('# Requires bd_helpers.tcl (apply_hwh_params, latest_vlnv) and hwh_params.tcl.')
    w('')
    # hierarchy cells
    hiers = set()
    for m in mods.values():
        parts = m['full'].split('/')[:-1]
        for i in range(1, len(parts) + 1):
            hiers.add('/'.join(parts[:i]))
    for h in sorted(hiers, key=lambda s: s.count('/')):
        w('create_bd_cell -type hier %s' % h)
    w('')
    # cells
    for inst, m in mods.items():
        vendor, lib, name, ver = m['vlnv'].split(':')
        if lib == 'module_ref':
            w('create_bd_cell -type module -reference %s %s' % (name, m['full']))
        else:
            w('create_bd_cell -type ip -vlnv [latest_vlnv %s:%s:%s] %s' % (vendor, lib, name, m['full']))
    w('')
    w('apply_all_hwh_params $hwh_params')
    w('')
    # external interface ports
    bus_members = defaultdict(list)   # busname -> [(cellpath, busif, type, vlnv)]
    for m in mods.values():
        for b in m['buses']:
            if b['busname'] and b['busname'] != '__NOC__':
                bus_members[b['busname']].append((m['full'], b['name'], b['type'], b['vlnv']))
    w('# external interface ports')
    for e in ext_intf:
        members = bus_members.get(e['busname'], [])
        if not members:
            print('warning: external interface %s has no member' % e['name'])
            continue
        vlnv = members[0][3]
        v, l, n, ver = vlnv.split(':')
        mode = 'Slave' if e['type'] in ('TARGET', 'SLAVE') else 'Master'
        w('create_bd_intf_port -mode %s -vlnv %s:%s:%s_rtl:%s %s' % (mode, v, l, n, ver, e['name']))
        for cell, bif, _, _ in members:
            if '/' in cell:
                w('connect_bd_intf_net [get_bd_intf_ports %s] [get_bd_intf_pins /[_lift_pin %s/%s {} %s 1]]' % (e['name'], cell, bif, e['name']))
            else:
                w('connect_bd_intf_net [get_bd_intf_ports %s] [get_bd_intf_pins %s/%s]' % (e['name'], cell, bif))
    ext_busnames = {e['busname'] for e in ext_intf}
    w('')
    w('# interface connections')
    covered = set()   # (cellpath, port) carried by an interface connection
    for bn, members in bus_members.items():
        if bn in ext_busnames:
            for cell, bif, _, _ in members:
                for m in mods.values():
                    if m['full'] == cell:
                        for b in m['buses']:
                            if b['name'] == bif:
                                covered.update((cell, p) for p in b['ports'])
            continue
        if len(members) != 2:
            print('warning: bus %s has %d members, skipped' % (bn, len(members)))
            continue
        (c1, b1, _, _), (c2, b2, _, _) = members
        w('xconnect_intf %s %s/%s %s/%s' % (bn, c1, b1, c2, b2))
        for cell, bif in ((c1, b1), (c2, b2)):
            for m in mods.values():
                if m['full'] == cell:
                    for b in m['buses']:
                        if b['name'] == bif:
                            covered.update((cell, p) for p in b['ports'])
    w('')
    # port nets
    w('# port connections')
    nets = defaultdict(list)
    for m in mods.values():
        for p in m['ports']:
            if (m['full'], p['name']) in covered:
                continue
            if not p['sig'] or p['sig'] == '__NOC__':
                continue
            nets[p['sig']].append((m['full'], p['name'], p['dir']))
    ext_sig = {}
    for p in ext_ports:
        ext_sig[p['sig']] = p
    for sig, ends in sorted(nets.items()):
        if len(ends) < 2:
            if sig in ext_sig:
                print('warning: external scalar port %s not generated' % sig)
            continue
        w('xconnect_net %s %s' % (sig, ' '.join('%s/%s' % (c, p) for c, p, _ in ends)))
    w('')
    w('# address map')
    for x in memranges:
        owner = mods.get(x['owner'])
        slave = mods.get(x['inst'])
        if not owner or not slave:
            continue
        base = int(x['base'], 16)
        rng = int(x['high'], 16) - base + 1
        w('assign_bd_address -offset 0x%08X -range 0x%08X -target_address_space '
          '[get_bd_addr_spaces %s/%s] [get_bd_addr_segs %s/%s/*] -force'
          % (base, rng, owner['full'], addr_space(owner, x['master']), slave['full'], x['slave']))
    w('')
    w('# second pass: parameters that propagation reset after wiring (user values win)')
    w('apply_all_hwh_params $hwh_params 1')
    with open(os.path.join(outdir, 'bd_from_hwh.tcl'), 'w', newline='\n') as f:
        f.write('\n'.join(L) + '\n')

    P = ['# Generated by hwh2bd.py - parameters of every cell in the boot HWH.',
         'set hwh_params [dict create]']
    for m in mods.values():
        kv = ' '.join('%s %s' % (tcl_quote(k), tcl_quote(v)) for k, v in m['params'].items()
                      if k not in SKIP_PARAMS)
        P.append('dict set hwh_params %s [list %s]' % (m['full'], kv))
    with open(os.path.join(outdir, 'hwh_params.tcl'), 'w', newline='\n') as f:
        f.write('\n'.join(P) + '\n')


def addr_space(owner, master_bif):
    if owner['vlnv'].startswith('xilinx.com:ip:zynq_ultra_ps_e'):
        return 'Data'
    return master_bif


if __name__ == '__main__':
    generate(sys.argv[1], sys.argv[2])
